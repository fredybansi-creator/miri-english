// Speech: recognition (Safari webkitSpeechRecognition) and text-to-speech.
import { getState } from './store.js';
import { SUPABASE_URL } from './config.js';

const TTS_URL = `${SUPABASE_URL}/functions/v1/tts`;

const SR = window.SpeechRecognition || window.webkitSpeechRecognition;
export const canListen = !!SR;
export const canSpeak = 'speechSynthesis' in window;

let voices = [];
function loadVoices() {
  voices = window.speechSynthesis.getVoices();
  window.dispatchEvent(new Event('voices-loaded'));
}
if (canSpeak) {
  loadVoices();
  window.speechSynthesis.addEventListener?.('voiceschanged', loadVoices);
  // iOS sometimes fills the list late and never fires voiceschanged
  setTimeout(loadVoices, 800);
}

// iPhone Safari only allows speechSynthesis after it was started once by a tap. Raluca's replies are
// spoken automatically (after the AI answers), so "unlock" the device voice on the first tap
// with a silent utterance. Same for the shared <audio> element below.
let unlocked = false;
function unlockAudio() {
  if (unlocked) return;
  unlocked = true;
  try {
    if (canSpeak) {
      const u = new SpeechSynthesisUtterance(' ');
      u.volume = 0;
      window.speechSynthesis.speak(u);
    }
  } catch { /* ignore */ }
  document.removeEventListener('touchend', unlockAudio, true);
  document.removeEventListener('click', unlockAudio, true);
}
document.addEventListener('touchend', unlockAudio, true);
document.addEventListener('click', unlockAudio, true);

// Best-sounding native English voices first (Edge/Windows "Natural" voices, Apple, Google).
const PREFERRED = {
  'en-US': ['Microsoft Ava Online', 'Microsoft Jenny Online', 'Microsoft Aria Online', 'Microsoft Andrew Online', 'Microsoft Guy Online',
    'Ava', 'Zoe', 'Evan', 'Nathan', 'Allison', 'Samantha', 'Google US English', 'Microsoft Zira', 'Microsoft David'],
  'en-GB': ['Microsoft Sonia Online', 'Microsoft Libby Online', 'Microsoft Ryan Online', 'Serena', 'Kate', 'Jamie', 'Daniel', 'Arthur',
    'Google UK English Female', 'Google UK English Male', 'Microsoft Hazel', 'Microsoft George'],
};

const norm = (v) => (v.lang || '').replace('_', '-');
const id = (v) => `${v.name} ${v.voiceURI || ''}`;

// Quality tier from the voice's name or internal id (Apple: com.apple.voice.premium.en-US.Ava).
export function voiceQuality(v) {
  const s = id(v).toLowerCase();
  if (/premium|neural|natural|online/.test(s)) return 3;
  if (/enhanced|siri/.test(s)) return 2;
  // novelty / joke voices (and the robotic "Eloquence" set) – never use these
  if (/eloquence|novelty|\b(bad news|bubbles|whisper|zarvox|trinoids|cellos|bells|good news|organ|superstar|albert|fred|junior|ralph|kathy|grandma|grandpa|rocko|shelley|flo|eddy|reed|sandy|boing|jester|wobble)\b/.test(s)) return 0;
  return 1;
}

export function englishVoices() {
  if (!voices.length && canSpeak) voices = window.speechSynthesis.getVoices();
  return voices.filter((v) => /^en(-|$)/i.test(norm(v)));
}

// Only ever pick an English voice – never the German system default.
// Order: her own choice → best quality tier → preferred names → local voice.
function pickVoice(lang) {
  const english = englishVoices();
  const chosen = getState().settings.deviceVoice;
  if (chosen) {
    const v = english.find((x) => x.voiceURI === chosen) || english.find((x) => x.name === chosen);
    if (v) return v;
  }
  const exact = english.filter((v) => norm(v).toLowerCase() === lang.toLowerCase());
  const pool = exact.length ? exact : english;
  if (!pool.length) return null;
  const names = PREFERRED[lang] || PREFERRED['en-US'];
  const rank = (v) => {
    const i = names.findIndex((n) => v.name.startsWith(n));
    return voiceQuality(v) * 100 - (i < 0 ? 50 : i) + (v.localService ? 1 : 0);
  };
  return pool.slice().sort((a, b) => rank(b) - rank(a))[0];
}

// ---------------------------------------------------------------- natural voice (ElevenLabs via Supabase)
// ---------------------------------------------------------------- which voice says what
//   role 'main' / 'friend' (fixed lesson sentences) → Kokoro mp3 files in /audio (free, offline,
//                                                      generated by tools/make_audio.py)
//   role 'sam'   (Raluca the fox in the chat)          → ElevenLabs via Supabase (natural, cached)
//   role 'coach' and anything not pre-generated      → device voice
// One shared <audio> element: on iPhone it is "unlocked" by the first tap and can then play
// later sentences too. If a file or the cloud voice fails, we fall back to the device voice.
const audio = typeof Audio !== 'undefined' ? new Audio() : null;
if (audio) audio.preload = 'auto';
let elevenFailures = 0;

let manifest = null; // { keys: { 'us-main': Set, 'us-friend': Set, 'uk-main': Set, 'uk-friend': Set } }
fetch('audio/manifest.json', { cache: 'no-cache' })
  .then((r) => (r.ok ? r.json() : null))
  .then((m) => {
    if (m) manifest = { ...m, keys: Object.fromEntries(Object.entries(m.keys).map(([k, v]) => [k, new Set(v)])) };
  })
  .catch(() => {});

const normText = (t) => String(t).replace(/\s+/g, ' ').trim();

/** FNV-1a (32 bit) over code points + length – must match key() in tools/make_audio.py. */
export function audioKey(text) {
  const t = normText(text);
  let h = 0x811c9dc5;
  for (const ch of t) {
    h ^= ch.codePointAt(0);
    h = Math.imul(h, 0x01000193) >>> 0;
  }
  return `${h.toString(16).padStart(8, '0')}${[...t].length.toString(16)}`;
}

const accentKey = () => (getState().settings.accent === 'en-GB' ? 'uk' : 'us');

function kokoroUrl(text, role) {
  if (!manifest || getState().settings.naturalVoice === false) return null;
  const set = `${accentKey()}-${role === 'friend' ? 'friend' : 'main'}`;
  const k = audioKey(text);
  return manifest.keys[set]?.has(k) ? `audio/${set}/${k}.mp3` : null;
}

function elevenUrl(text) {
  if (getState().settings.samVoice === false || elevenFailures >= 3) return null;
  return `${TTS_URL}?v=${accentKey()}&r=friend&t=${encodeURIComponent(normText(text))}`;
}

// Tells listeners (e.g. Raluca the fox) when something is being read aloud.
function emitTts(state, role) {
  window.dispatchEvent(new CustomEvent('tts', { detail: { state, role } }));
}

export function say(text, opts = {}) {
  if (!text) return Promise.resolve();
  emitTts('start', opts.role || 'main');
  const p = sayInner(text, opts);
  p.finally(() => emitTts('end', opts.role || 'main'));
  return p;
}

function sayInner(text, { rate, role = 'main' } = {}) {
  stopSpeaking();
  const isSam = role === 'sam';
  const url = !audio ? null : isSam ? elevenUrl(text) : (role === 'main' || role === 'friend') ? kokoroUrl(text, role) : null;
  if (!url) return browserSay(text, { rate });
  return new Promise((resolve) => {
    let fellBack = false;
    const fallback = () => {
      if (fellBack) return;
      fellBack = true;
      if (isSam) elevenFailures++;
      browserSay(text, { rate }).then(resolve);
    };
    audio.onended = () => resolve();
    audio.onerror = fallback;
    audio.src = url;
    // slow button passes ~0.7; the "langsam" setting is 0.8
    const r = rate ?? getState().settings.rate;
    audio.playbackRate = r < 0.75 ? 0.75 : r < 0.9 ? 0.85 : 1;
    const p = audio.play();
    if (p) p.catch((e) => { if (e && e.name === 'NotAllowedError') resolve(); else fallback(); });
  });
}

/** Play a sample with one specific device voice (for the voice picker). */
export function testDeviceVoice(voiceURI, text = "Hi Miri! It's been ages – what have you been up to?") {
  if (!canSpeak) return;
  const v = englishVoices().find((x) => x.voiceURI === voiceURI);
  window.speechSynthesis.cancel();
  const u = new SpeechSynthesisUtterance(text);
  if (v) { u.voice = v; u.lang = v.lang; }
  u.rate = getState().settings.rate;
  window.speechSynthesis.speak(u);
}

function browserSay(text, { rate } = {}) {
  if (!canSpeak || !text) return Promise.resolve();
  const synth = window.speechSynthesis;
  synth.cancel();
  const s = getState().settings;
  const u = new SpeechSynthesisUtterance(text);
  u.lang = s.accent;
  const v = pickVoice(s.accent);
  if (v) { u.voice = v; u.lang = v.lang; }
  else if (voices.length) window.dispatchEvent(new Event('no-english-voice')); // only non-English voices installed
  u.rate = rate ?? s.rate;
  return new Promise((resolve) => {
    u.onend = u.onerror = () => resolve();
    synth.speak(u);
  });
}

export function stopSpeaking() {
  if (canSpeak) window.speechSynthesis.cancel();
  if (audio && !audio.paused) audio.pause();
}

/**
 * Start listening. Returns { promise, stop, abort }.
 * promise resolves { text, alternatives } or rejects with { code }:
 * 'not-allowed' | 'service-not-allowed' | 'no-speech' | 'network' | 'audio-capture' | 'aborted' | 'unsupported'
 */
export function listen({ onInterim } = {}) {
  if (!SR) {
    return { promise: Promise.reject(Object.assign(new Error('unsupported'), { code: 'unsupported' })), stop() {}, abort() {} };
  }
  stopSpeaking();
  const rec = new SR();
  rec.lang = getState().settings.accent;
  rec.interimResults = true;
  rec.maxAlternatives = 3;
  rec.continuous = false;

  let finals = [];
  let interim = '';
  let error = null;
  let settled = false;
  let finish = () => {};
  const timers = [];

  const promise = new Promise((resolve, reject) => {
    // Settles exactly once – from onend, or forced when iPhone Safari never sends onend.
    finish = (forceCode) => {
      if (settled) return;
      settled = true;
      timers.forEach(clearTimeout);
      rec.onresult = rec.onerror = rec.onend = null;
      if (forceCode === 'aborted') {
        reject(Object.assign(new Error('aborted'), { code: 'aborted' }));
      } else if (finals.length) {
        const text = finals.map((a) => a[0]).join(' ').trim();
        const alternatives = finals.length === 1 ? finals[0] : [text];
        resolve({ text, alternatives });
      } else if (interim.trim()) {
        resolve({ text: interim.trim(), alternatives: [interim.trim()] });
      } else {
        const code = error || forceCode || 'no-speech';
        reject(Object.assign(new Error(code), { code }));
      }
    };
    rec.onresult = (e) => {
      const fin = [];
      interim = '';
      for (let i = 0; i < e.results.length; i++) {
        const r = e.results[i];
        if (r.isFinal) fin.push(Array.from(r).map((a) => a.transcript.trim()));
        else interim += r[0].transcript;
      }
      finals = fin;
      onInterim?.((fin.map((a) => a[0]).join(' ') + ' ' + interim).trim());
    };
    rec.onerror = (e) => { error = e.error; };
    rec.onend = () => finish();
  });

  try { rec.start(); } catch (e) {
    return { promise: Promise.reject(Object.assign(new Error('start-failed'), { code: 'start-failed' })), stop() {}, abort() {} };
  }

  // iPhone Safari sometimes ignores stop() and never fires onend – the mic then stays on forever.
  // So: stop() → abort() after a moment → give up waiting and settle the promise ourselves.
  let stopping = false;
  const stop = () => {
    if (settled || stopping) return;
    stopping = true;
    try { rec.stop(); } catch { /* ignore */ }
    timers.push(setTimeout(() => { try { rec.abort(); } catch { /* ignore */ } }, 1200));
    timers.push(setTimeout(() => finish(), 2500));
  };
  // Throw away what was heard (leaving the screen) – settles right away.
  const abort = () => {
    if (settled) return;
    try { rec.abort(); } catch { /* ignore */ }
    finish('aborted');
  };
  return { promise, stop, abort };
}

export function errorMessage(code) {
  switch (code) {
    case 'not-allowed':
    case 'service-not-allowed':
      return 'Mikrofon oder Spracherkennung ist nicht erlaubt. Auf dem iPhone: Einstellungen › Safari › Mikrofon › „Erlauben“ – und unter Einstellungen › Allgemein › Tastatur „Diktierfunktion“ einschalten. Bis dahin kannst du mit dem Mikrofon der Tastatur diktieren.';
    case 'no-speech':
      return 'Ich habe nichts gehört. Tippe auf das Mikrofon und sprich gleich los.';
    case 'network':
      return 'Die Spracherkennung braucht Internet. Prüf deine Verbindung und versuch es nochmal.';
    case 'audio-capture':
      return 'Kein Mikrofon gefunden.';
    case 'unsupported':
      return 'Dieser Browser kann hier nicht zuhören. Nutze das Mikrofon auf deiner Tastatur zum Diktieren.';
    default:
      return 'Das hat nicht geklappt. Versuch es nochmal oder diktiere mit der Tastatur.';
  }
}
